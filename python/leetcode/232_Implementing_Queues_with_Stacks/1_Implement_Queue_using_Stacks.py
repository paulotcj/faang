#problem: https://leetcode.com/problems/implement-queue-using-stacks/description/
from typing import List, Dict

#-------------------------------------------------------------------------
class MyQueue :
    #-------------------------------------------------------------------------
    def __init__( self ) :
        self.stack1 : list[int] = []
        self.stack2 : list[int] = []
    #-------------------------------------------------------------------------
    #-------------------------------------------------------------------------
    def empty( self ) -> bool :
        return_result : bool = not ( self.stack1 or self.stack2 )
        return return_result
    #------------------------------------------------------------------------- 
    #-------------------------------------------------------------------------
    def push( self , x : int ) -> None :
        self.stack1.append(x)
    #-------------------------------------------------------------------------
    #-------------------------------------------------------------------------
    def peek(self) -> int:
        if self.stack2:
            return self.stack2[-1]
        
        if self.stack1:
            self.__transfer()
            return self.stack2[-1]
    #-------------------------------------------------------------------------    
    #-------------------------------------------------------------------------
    def __transfer(self):
        #-----------------------------------
        while self.stack1:
            temp : int = self.stack1.pop()
            self.stack2.append(temp)
        #-----------------------------------
    #-------------------------------------------------------------------------
    #-------------------------------------------------------------------------
    def pop(self) -> int:
        if self.stack2:
            return self.stack2.pop()
        
        if self.stack1:
            #-----------------------------------
            while self.stack1:
                temp = self.stack1.pop()
                self.stack2.append(temp)
            #-----------------------------------
            return_val : int = self.stack2.pop()
            return return_val
    #-------------------------------------------------------------------------
#-------------------------------------------------------------------------

